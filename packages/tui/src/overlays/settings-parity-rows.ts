/** Rows for one tab, in the reference's declaration order. */
export function rowsForTab(tab: string): readonly ParityRow[] {
	return OMP_PARITY_ROWS.filter((row) => row.tab === tab);
}

/** Rows in one group, in the reference's declaration order. */
export function rowsForGroup(tab: string, group: string): readonly ParityRow[] {
	return OMP_PARITY_ROWS.filter((row) => row.tab === tab && row.group === group);
}

/** Counts by status. */
export function parityStatusCounts(): Record<ParityStatus, number> {
	const counts: Record<string, number> = {};
	for (const row of OMP_PARITY_ROWS) counts[row.status] = (counts[row.status] ?? 0) + 1;
	return counts as Record<ParityStatus, number>;
}

/** Every row that is not usable yet, with its reason. */
export function unavailableRows(): readonly ParityRow[] {
	return OMP_PARITY_ROWS.filter((row) => row.status !== "wired" && row.status !== "pi-specific");
}
