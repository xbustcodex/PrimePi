/**
 * The complete OMP Settings parity contract.
 *
 * ## What this is
 *
 * Every setting the reference's Settings panel renders at `eabd6b99c6`,
 * transcribed field for field: id, tab, group, row label, description,
 * control type, default, selector options in their source order, conditional
 * visibility, sensitivity, and the row's parity status against PrimePi.
 *
 * ## Why every row is here, including the unmigrated ones
 *
 * A setting whose subsystem is not migrated is recorded as
 * `omp-present-unmigrated`, not omitted. The panel renders those rows as
 * disabled markers at their reference locations, so a user can navigate the
 * reference's structure today and a later wave activates each row **in place**.
 * Omitting them would make the panel smaller than the reference now and
 * structurally different later, which is worse than showing an honest marker.
 *
 * ## Generated, then committed
 *
 * Produced by scanning the reference checkout. The count is asserted in CI
 * against the per-tab distribution below, so an extraction that silently loses
 * rows fails a test rather than shipping a smaller panel.
 *
 * ## Status vocabulary
 *
 * - `wired` — registered in PrimePi's typed registry and consumed.
 * - `pi-specific` — PrimePi has the capability and the reference does not.
 * - `omp-present-unmigrated` — the reference shows it; the subsystem is not
 *   migrated. Renders disabled.
 * - `deferred` — recorded for parity; no consumer identified yet.
 * - `excluded` — a standing product exclusion.
 */

/** Parity state of one reference setting. */
export type ParityStatus = "wired" | "pi-specific" | "omp-present-unmigrated" | "deferred" | "excluded";

/** One selector option, in the reference's order. */
export interface ParityOption {
	readonly value: string;
	readonly label: string;
	readonly description?: string;
}

/** One reference setting, transcribed. */
export interface ParityRow {
	/** The reference's registry id, e.g. `memory.backend`. */
	readonly id: string;
	readonly tab: string;
	/** Section heading within the tab, or null when the reference groups it. */
	readonly group: string | null;
	/** The owner-visible label. */
	readonly label: string;
	readonly description?: string;
	readonly type: string;
	readonly default?: string;
	/** Selector options, in the reference's render order. */
	readonly options?: readonly ParityOption[];
	/** Permitted values for an enum or cycle control. */
	readonly values?: readonly string[];
	/** Named condition; the reference evaluates it before showing the row. */
	readonly condition?: string;
	/** The value is masked wherever it would be displayed. */
	readonly secret?: boolean;
	readonly warning?: string;
	readonly status: ParityStatus;
	/** The PrimePi registry key, when mapped. */
	readonly piKey?: string;
	/** Why a row is not usable yet. Required for every non-wired status. */
	readonly note?: string;
}

